text = input()

print("Initial String with use of Triple Quotes:")
print(text)

print("\nEscaping Single Quote:")
print(text.replace("'", "\\'"))

print("\nEscaping Double Quotes:")
print(text.replace('"', '\\"'))

print("\nEscaping Backslashes:")
print(r"C:\Python\Geeks\\")

print("\nTab:")
print("Hi\tGeeks")

print("\nNew Line:")
print("Python\nGeeks")